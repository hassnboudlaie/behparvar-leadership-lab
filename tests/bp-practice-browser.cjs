/* Browser-level practice workflow acceptance: additive; never touches shared learner records. */
"use strict";
const {chromium}=require("playwright");
const assert=require("node:assert/strict");
(async()=>{
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const base=process.env.AUDIT_URL||"http://127.0.0.1:8765/";
const errors=[];
try {
 const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,locale:"fa-IR"});
 const page=await context.newPage();
 page.on("pageerror",e=>errors.push(String(e)));
 await page.goto(base+"?audience=supervisors",{waitUntil:"load"});
 await page.locator('#welcome [data-open="course"]').click();
 await page.locator('#course [data-course-session="5"]').click();
 await page.locator("#session5.view.active").waitFor();
 await page.locator("#bp-practice-5").waitFor();
 const host=page.locator("#bp-practice-5");
 await host.locator("summary").first().click();
 await host.locator('[data-bp-scene-choice="5:0"]').waitFor({state:"visible"});
 const supervisorContext=await host.locator(".bp-practice-context").innerText();
 assert.ok(supervisorContext.length>40,"Rich practice context remains visible");
 await host.locator('[data-bp-scene-choice="5:1"]').click();
 assert.equal(await host.locator('.bp-practice-options [aria-pressed="true"]').count(),1);
 assert.ok((await host.locator(".bp-practice-feedback").innerText()).length>25);
 await host.locator('[data-bp-practice-tab="5:dialogue"]').first().click();
 await host.locator('[data-bp-dialogue-id="delegation"]').click();
 assert.ok((await host.locator(".bp-practice-drama").innerText()).length>90);
 assert.equal(await host.locator(".bp-practice-weak .bp-speech").count(),2);
 await host.locator(".bp-practice-drama details").nth(1).locator("summary").click();
 assert.equal(await host.locator(".bp-practice-better .bp-speech").count(),6);
 await host.locator('[data-bp-practice-tab="5:transfer"]').first().click();
 await host.locator('[data-bp-practice-note="5:behavior"]').fill("سؤال باز پیش از قضاوت");
 await host.locator('[data-bp-practice-note="5:opportunity"]').fill("تحویل شیفت بعدی");
 const stateBefore=await page.evaluate(()=>JSON.parse(localStorage.getItem("bp_practice_action_v1_supervisors_session5")||"{}"));
 assert.equal(stateBefore.behavior,"سؤال باز پیش از قضاوت");
 assert.equal(stateBefore.opportunity,"تحویل شیفت بعدی");
 await page.reload({waitUntil:"load"});
 await page.locator("#bp-practice-5 summary").first().click();
 await page.locator('#bp-practice-5 [data-bp-practice-tab="5:transfer"]').first().click();
 assert.equal(await page.locator('[data-bp-practice-note="5:behavior"]').inputValue(),"سؤال باز پیش از قضاوت");
 await page.goto(base+"?audience=managers",{waitUntil:"load"});
 await page.locator('#welcome [data-open="course"]').click();
 await page.locator('#course [data-course-session="5"]').click();
 await page.locator("#session5.view.active").waitFor();
 await page.locator("#bp-practice-5 summary").first().click();
 assert.notEqual(await page.locator("#bp-practice-5 .bp-practice-context").innerText(),supervisorContext,"Distinct manager/supervisor practice case");
 await page.locator('#bp-practice-5 [data-bp-practice-tab="5:transfer"]').first().click();
 assert.equal(await page.locator('[data-bp-practice-note="5:behavior"]').inputValue(),"");
 const old=await page.evaluate(()=>JSON.parse(localStorage.getItem("bp_practice_action_v1_supervisors_session5")||"{}"));
 assert.equal(old.behavior,"سؤال باز پیش از قضاوت");
 const routes=await page.evaluate(()=>{
 const parts=["m1","m2","leaders","techniques","visuals","diseases","quiz"];
 return [1,2,5,6].flatMap(n=>parts.map(p=>n===1?p:"session"+n+"-"+p)).filter(id=>!!document.getElementById(id)).length;
 });
 assert.equal(routes,28);
 assert.deepEqual(errors,[]);
 console.log("PASS practice browser: decision -> trade-off -> distinct roleplay -> 4-field action -> refresh persistence -> role separation; 28 retained legacy routes, standalone Sessions 3/4; mobile 390px");
 await context.close();
} finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
