  await page.locator(section+" [data-simple-eval]").first().selectOption("تا حدی مشاهده شد");
  await page.locator(section+" [data-simple-evidence]").first().fill("در جمله مربوط به زمان گزارش وضعیت");
  await page.locator(section+" [data-simple-answer]").first().fill("نقطه عطف زمانی بود که سرپرست تولید برداشت اولیه را اصلاح کرد.");
