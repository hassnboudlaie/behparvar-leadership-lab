  const report=await page.evaluate(()=>window.__copiedObserverText);
  assert.ok(report.includes("مشاهده‌گر کلاس")&&report.includes("تا حدی مشاهده شد"));
  assert.ok(report.includes("سرپرست تولید برداشت اولیه را اصلاح کرد"));
  assert.ok((await page.locator(section+" [data-simple-copy-status]").innerText()).includes("کپی شد"));
